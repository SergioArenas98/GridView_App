"""Home upcoming-section EXPERIMENT (Step 49B.1). Python 3 stdlib only.

    python build.py           write the experiment files into this folder
    python build.py --check   verify the written files are current (no write)

Development-only. Not an approved design, not a fixture, not a Flutter
contract. Every file is derived from the Home consolidation pilot
(../../consolidation-pilot/home/, pixel-identical to the approved
../../refinement-01/), which is only read, never written.

The one change (STATUS-ABSENCE-DECISIONS.md section 2, accepted direction
H-R1): the frozen Home scenario is the hero "Next Grand Prix" (pre-event
phase) with a materialized calendar whose upcoming list is empty once the
featured round is excluded (availableEmpty). In exactly that state the
secondary "Upcoming events" section is omitted. Every other state keeps it;
the rule is documented, not simulated, because the prototype renders only
this one state. No copy is added or changed.

- index[.es].html: an experiment comment; the upcoming section removed.
- home.css: copied verbatim (its .upcoming rules become unused).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent.parent / "consolidation-pilot" / "home"

MAIN_OPEN = '<main class="home">\n'
EXPERIMENT_COMMENT = (
    "<!-- EXPERIMENT (Step 49B.1), development-only, not an approved design:\n"
    "     Home with the secondary upcoming section omitted in the state this\n"
    "     frozen scenario shows: hero \"Next Grand Prix\" (pre-event) and an\n"
    "     available but empty upcoming list (the featured round is excluded).\n"
    "     Derived from ../../consolidation-pilot/home/{name}. Generated by\n"
    "     build.py; edit the generator, not this file. -->\n"
)
UPCOMING = re.compile(
    r"(?:  <!-- H40–H41:[^\n]*-->\n)?  <section class=\"upcoming\" aria-labelledby=\"upcoming-title\">\n"
    r".*?  </section>\n\n",
    re.S,
)


def read(name: str) -> str:
    return (SOURCE / name).read_text(encoding="utf-8").replace("\r\n", "\n")


def page(name: str) -> str:
    html = read(name)
    found = UPCOMING.findall(html)
    assert len(found) == 1, (name, len(found))
    assert "upcoming__empty" in found[0] and 'href="#calendar"' in found[0]
    html = UPCOMING.sub("", html)
    assert html.count(MAIN_OPEN) == 1
    return html.replace(MAIN_OPEN, EXPERIMENT_COMMENT.format(name=name) + MAIN_OPEN)


def outputs() -> dict[str, str]:
    return {
        "index.html": page("index.html"),
        "index.es.html": page("index.es.html"),
        "home.css": read("home.css"),
    }


def main() -> None:
    check_only = "--check" in sys.argv
    stale = []
    for name, text in outputs().items():
        target = HERE / name
        current = target.exists() and target.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        if check_only:
            print(f"{'ok ' if current else 'STALE'} {name}")
            if not current:
                stale.append(name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    if check_only:
        assert not stale, f"stale: {stale}"
    else:
        print("wrote", ", ".join(outputs()))


if __name__ == "__main__":
    main()
