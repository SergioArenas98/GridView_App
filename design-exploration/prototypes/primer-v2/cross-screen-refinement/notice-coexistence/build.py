ICON = '<svg class="icon" aria-hidden="true"><use href="#i-cloud-off"/></svg>'


def notice(text: str, attrs: str = "") -> str:
    return f'<p class="notice" role="status"{attrs}>{ICON}<span>{text}</span></p>'


def sub(text: str, old: str, new: str, label: str) -> str:
    count = text.count(old)
    if count != 1:
        raise SystemExit(f"{label}: expected exactly one match, found {count}: {old[:70]!r}")
    return text.replace(old, new)


