# variant -> (source scenario, notice keys in N-1 order, extra comment)
DETAIL = {
    "failed": ("index", ["failed"], ""),
    "partial": ("partial", ["partial"], ""),
    "failed-partial": ("partial", ["failed", "partial"], ""),
    "combined-partial": ("partial", ["combined", "partial"],
                         "\n     HYPOTHETICAL: failure + stale + partial is not reachable in today's\n"
                         "     state derivation (a partial profile has no freshness; a 404 clears\n"
                         "     the failure). Layout test only. Combined text = N-2 COPY CANDIDATE."),
    "combined-b-partial": ("partial", ["combined_b", "partial"],
                           "\n     HYPOTHETICAL (as combined-partial), with N-2 COPY CANDIDATE B\n"
                           "     (Step 49D.2)."),
    "stacked-partial": ("partial", ["failed", "stale", "partial"],
                        "\n     HYPOTHETICAL (as combined-partial): the three existing notices\n"
                        "     stacked, for comparison with the combined notice."),
}


def detail(variant: str, lang: str) -> str:
    scenario, keys, extra = DETAIL[variant]
    name = f"{scenario}.html" if lang == "en" else f"{scenario}.es.html"
    c = COPY[lang]
    s = (DD / name).read_text(encoding="utf-8")
    s = sub(s, DD_SOURCE_COMMENT, DD_COMMENT.format(variant=variant, name=name, extra=extra), "comment")
    s = sub(s, '<link rel="stylesheet" href="dd.css">',
            '<link rel="stylesheet" href="../../consolidation-pilot/driver-detail/dd.css">\n'
            '<link rel="stylesheet" href="notice-coexistence.css">', "css")
    block = '<div class="page-notice">' + "".join(notice(c[k], f' data-kind="{k}"') for k in keys) + "</div>"
    if scenario == "partial":
        s = sub(s, PARTIAL_BLOCK.format(partial=c["partial"]), block, "partial block")
    else:
        s = sub(s, '<main class="page">\n', f'<main class="page">\n{block}\n', "notice block")
    return s


def outputs() -> dict[str, str]:
    out = {"calendar.html": calendar("en"), "calendar.es.html": calendar("es")}
    for variant in DETAIL:
        out[f"detail-{variant}.html"] = detail(variant, "en")
        out[f"detail-{variant}.es.html"] = detail(variant, "es")
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
