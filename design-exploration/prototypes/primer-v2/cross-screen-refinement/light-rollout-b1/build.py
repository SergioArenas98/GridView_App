def exceptions(s: str, page_id: str, variant: str, lang: str) -> str:
    """The two Step 53C.1 markup exceptions; every other page passes through."""
    if page_id == "lt14":
        t = LT14_TEXT[lang]
        chevron = re.search(r'  <symbol id="i-chevron"[^\n]*\n', s).group(0)
        s = sub(s, chevron, chevron + CHECK_SYMBOL, "lt14 symbol")
        s = sub(s, t["note"][0], t["note"][1], "lt14 note")
        ol = '<ol class="rounds" aria-labelledby="season">\n'
        s = sub(s, ol, ol + LT14_ROW.format(round=t["round"], done=t["done"]), "lt14 row")
    if page_id == "td-states" and variant == "light":
        for old, new in TD_LIGHT_CAPTIONS:
            s = sub(s, old, new, "td caption")
    return s


def sub(text: str, old: str, new: str, label: str) -> str:
    found = text.count(old)
    if found != 1:
        raise SystemExit(f"{label}: expected 1 match, found {found}: {old[:70]!r}")
    return text.replace(old, new)


def rebase(text: str, src_dir: str) -> str:
    """Rewrite each relative href/src so it resolves to the same file from HERE."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        if not url or url.startswith(("#", "http:", "https:", "data:", "mailto:", "/")):
            return m.group(0)
        cut = re.search(r"[?#]", url)
        path, tail = (url[:cut.start()], url[cut.start():]) if cut else (url, "")
        target = posixpath.normpath(posixpath.join(src_dir, path))
        return f'{attr}="{posixpath.relpath(target, HERE_REL)}{tail}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, text)


def derive(page_id: str, variant: str, lang: str) -> str:
    src = PAGES[page_id]
    name = f"{src}.html" if lang == "en" else f"{src}.es.html"
    path = PRIMER / name
    s = path.read_text(encoding="utf-8")
    comment = COMMENT.format(variant=variant, src=name)
    generated = [g for g in GENERATED if g in s]
    if generated:
        s = sub(s, generated[0], comment, "comment")
    else:
        s = sub(s, "<body>\n", f"<body>\n{comment}\n", "comment")
    s = exceptions(s, page_id, variant, lang)
    s = rebase(s, path.parent.relative_to(PRIMER).as_posix())
    s = re.sub(r"(?m)^[ \t]+$", "", s)   # whitespace-only lines render nothing
    links = "".join(f'<link rel="stylesheet" href="{c}">\n' for c in SPECIMEN.get(page_id, []) + VARIANTS[variant])
    return sub(s, "</head>", f"{links}</head>", "stylesheets")


def outputs() -> dict[str, str]:
    out: dict[str, str] = {}
    for page_id in PAGES:
        for variant in VARIANTS:
            if page_id not in ONLY.get(variant, PAGES):
                continue
            for lang in ("en", "es"):
                out[f"{page_id}-{variant}{'' if lang == 'en' else '.es'}.html"] = derive(page_id, variant, lang)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
