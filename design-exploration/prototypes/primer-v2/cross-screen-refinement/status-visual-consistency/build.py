"""Status visual consistency EXPERIMENT (Step 49E). Python 3 stdlib only.

    python build.py           write the experiment pages into this folder
    python build.py --check   verify the written pages are current (no write)

Not an approved design, not a fixture, not a Flutter contract. Every page is
derived by asserted text substitutions from the consolidation pilots (each
pixel-identical to its approved prototype), which are only read. Local links
point back to the pilot folders, so stylesheets and scripts are the pilots'
own; status-visual.css only adds two rules.

Proposed pages (the pilot pages themselves are the "current" reference):
- gp-states[.es].html   <- grand-prix-detail/states: "Format unknown" dashed
  (was the filled context chip); session "Status unknown" as a compact dashed
  chip (was plain text like "Scheduled"); finish "Status unknown" dashed (was
  the solid outline shared with DNF); "Provisional" with the dagger (was the
  outline chip shared with "Not available").
- cd-states[.es].html   <- circuit-detail/states: "Format unknown" dashed.
- dd-states / td-states <- driver-detail, team-detail/states: dagger on
  "Provisional".
- notices-{current,proposed}-{failed-partial,combined-partial,stale}[.es].html
  <- driver-detail/partial and index: stacked notices with the current
  cloud-off icon on every notice vs a cause icon from the existing set
  (failure and failure+stale: alert; stale: clock; incomplete: help). The
  combined text is the N-2 wording approved in Step 49D.3 (not ARB copy).

Words, data and accessible names are unchanged; the dagger is aria-hidden.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
PILOT = HERE.parent.parent / "consolidation-pilot"
GENERATED = "<!-- Generated by build.py - edit the generator, not this file. -->"
COMMENT = (
    "<!-- EXPERIMENT (Step 49E), not an approved design: status visual\n"
    "     consistency, {what}. Derived from ../../consolidation-pilot/{src},\n"
    "     which is only read. Generated by build.py; edit the generator, not\n"
    "     this file. -->"
)
L10N = {
    "en": {"format": "Format unknown", "status": "Status unknown", "prov": "Provisional",
           "failed": "Update failed", "stale": "Details may be outdated",
           "partial": "Some profile information is unavailable",
           "combined": "Couldn't refresh. Saved data may be out of date."},
    "es": {"format": "Formato desconocido", "status": "Estado desconocido", "prov": "Provisional",
           "failed": "No se pudo actualizar", "stale": "Los detalles pueden estar desactualizados",
           "partial": "Parte de la información del perfil no está disponible",
           "combined": "No se pudo actualizar. Los datos guardados pueden estar desactualizados."},
}
DAGGER = '<span class="dagger" aria-hidden="true">†</span>'
CLOCK = '<symbol id="i-clock" viewBox="0 0 24 24"><circle cx="12" cy="12" r="10"/><path d="M12 6v6l4 2"/></symbol>'


def sub(text: str, old: str, new: str, label: str, count: int = 1) -> str:
    found = text.count(old)
    if found != count:
        raise SystemExit(f"{label}: expected {count} match(es), found {found}: {old[:70]!r}")
    return text.replace(old, new)


def rebase(text: str, screen: str) -> str:
    """Point every local href/src at the pilot folder (shared/, fonts, # unchanged)."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        if url.startswith(("../", "#", "http", "data:")):
            return m.group(0)
        return f'{attr}="../../consolidation-pilot/{screen}/{url}"'
    return re.sub(r'(href|src)="([^"]*)"', fix, text)


def derive(screen: str, page: str, lang: str, what: str) -> str:
    name = f"{page}.html" if lang == "en" else f"{page}.es.html"
    s = (PILOT / screen / name).read_text(encoding="utf-8")
    # The Standings pilot writes its generated-file comment with an em dash.
    generated = next(g for g in (GENERATED, GENERATED.replace(" - ", " — ")) if g in s)
    s = sub(s, generated, COMMENT.format(what=what, src=f"{screen}/{name}"), "comment")
    s = rebase(s, screen)
    s = sub(s, "</head>", '<link rel="stylesheet" href="status-visual.css">\n</head>', "css")
    return s


def gp(lang: str) -> str:
    t = L10N[lang]
    s = derive("grand-prix-detail", "states", lang, "Grand Prix states (A unknown, B provisional)")
    s = sub(s, f'<span class="chip chip--context">{t["format"]}</span>',
            f'<span class="chip chip--unknown">{t["format"]}</span>', "format")
    s = sub(s, f'<p class="sess__status"><span class="sess__state">{t["status"]}</span></p>',
            f'<p class="sess__status"><span class="chip chip--unknown chip--sm">{t["status"]}</span></p>', "session")
    s = sub(s, f'<span class="chip chip--outline chip--sm">{t["status"]}</span>',
            f'<span class="chip chip--unknown chip--sm">{t["status"]}</span>', "finish")
    s = sub(s, f'<span class="chip chip--outline">{t["prov"]}</span>',
            f'<span class="chip chip--outline">{DAGGER}{t["prov"]}</span>', "provisional", count=2)
    # Step 50B: the pilot's one whitespace-only line (inherited from the approved
    # prototype) becomes an empty line, so the page passes `git diff --check`.
    s = sub(s, '<li class="day">\n      \n      <ol class="sess-list">',
            '<li class="day">\n\n      <ol class="sess-list">', "whitespace-only line")
    return s


def cd(lang: str) -> str:
    t = L10N[lang]
    s = derive("circuit-detail", "states", lang, "Circuit states (A unknown format)")
    return sub(s, f'<span class="chip chip--context">{t["format"]}</span>',
               f'<span class="chip chip--unknown">{t["format"]}</span>', "format")


def provisional(screen: str, lang: str) -> str:
    t = L10N[lang]
    s = derive(screen, "states", lang, "provisional marker (B)")
    return sub(s, f'<span class="chip chip--outline">{t["prov"]}</span>',
               f'<span class="chip chip--outline">{DAGGER}{t["prov"]}</span>', "provisional")


def standings(lang: str) -> str:
    """Step 49E.1: the Standings compact row marker without the dagger.

    Size, outline, word, caption and accessible name unchanged; only the
    aria-hidden glyph is removed.
    """
    t = L10N[lang]
    s = derive("standings", "states", lang, "Standings provisional marker without the dagger (Step 49E.1)")
    return sub(s, f'<span class="chip chip--provisional">{DAGGER}{t["prov"]}</span>',
               f'<span class="chip chip--provisional">{t["prov"]}</span>', "standings dagger")


NOTICE_SETS = {
    "failed-partial": ("partial", ["failed", "partial"]),
    "combined-partial": ("partial", ["combined", "partial"]),
    "stale": ("index", ["stale"]),
}
ICONS = {
    "current": {"failed": "i-cloud-off", "combined": "i-cloud-off", "stale": "i-cloud-off", "partial": "i-cloud-off"},
    "proposed": {"failed": "i-alert", "combined": "i-alert", "stale": "i-clock", "partial": "i-help"},
}


def notices(variant: str, icons: str, lang: str) -> str:
    page, keys = NOTICE_SETS[variant]
    t = L10N[lang]
    s = derive("driver-detail", page, lang, f"notice icons ({icons}, {variant})")
    block = '<div class="page-notice">' + "".join(
        f'<p class="notice" role="status" data-kind="{k}"><svg class="icon" aria-hidden="true">'
        f'<use href="#{ICONS[icons][k]}"/></svg><span>{t[k]}</span></p>' for k in keys) + "</div>"
    if page == "partial":
        old = ('<div class="page-notice"><p class="notice" role="status"><svg class="icon" aria-hidden="true">'
               f'<use href="#i-cloud-off"/></svg><span>{t["partial"]}</span></p></div>')
        s = sub(s, old, block, "partial block")
    else:
        s = sub(s, '<main class="page">\n', f'<main class="page">\n{block}\n', "notice block")
    if icons == "proposed":
        # i-clock exists in the approved set (Grand Prix sprite); copied verbatim.
        s = sub(s, '<symbol id="i-help"', f'{CLOCK}\n  <symbol id="i-help"', "clock symbol")
    return s


def outputs() -> dict[str, str]:
    out: dict[str, str] = {}
    for lang in ("en", "es"):
        sfx = "" if lang == "en" else ".es"
        out[f"gp-states{sfx}.html"] = gp(lang)
        out[f"cd-states{sfx}.html"] = cd(lang)
        out[f"dd-states{sfx}.html"] = provisional("driver-detail", lang)
        out[f"td-states{sfx}.html"] = provisional("team-detail", lang)
        out[f"st-states{sfx}.html"] = standings(lang)
        for variant in NOTICE_SETS:
            for icons in ICONS:
                out[f"notices-{icons}-{variant}{sfx}.html"] = notices(variant, icons, lang)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
