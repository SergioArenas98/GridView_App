"""Primer V2 Light foundations EXPLORATION (Step 53A). Python 3 stdlib only.

    python build.py           write the exploration pages into this folder
    python build.py --check   verify the written pages are current (no write)

Not an approved palette, not a fixture, not a Flutter contract. Every page is
a consolidation-pilot page (each pixel-identical to its approved prototype),
which is only read. Three variants per page, from the same markup:

- "dark": the pilot plus the frozen Dark implementation overlays from
  ../dark-state-boundaries/ (candidate.css: A1 outline, flat oxide, Chalk
  ring on oxide; refine-focus.css: Chalk ring on every selector option, ring
  above decorative cells). This is the Dark reference the Light directions
  are compared with (DARK-THEME-ROLES.md, DK-1 to DK-3).
- "light-a" / "light-b": the same, plus light-roles.css (role map) and one
  direction file (light-a.css or light-b.css).
- "light-bm" (Step 53A.1, "B Motorsport", approved as LT-1): light-b plus
  light-bm.css, for Home, GP results and Standings (Explore added in 53B).
- "light-53b" (Step 53B): light-bm plus light-53b.css (focus and team-colour
  corrections), on the same four pages.

The derivation changes exactly two things: relative href/src values are
rebased so they resolve to the same files as from the pilot, and the
stylesheets above are linked last. Markup, words, data, accessible names and
scripts are unchanged (checks.mjs verifies it in the browser).
"""

from __future__ import annotations

import posixpath
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
PRIMER = HERE.parent.parent
PILOT = PRIMER / "consolidation-pilot"
HERE_REL = HERE.relative_to(PRIMER).as_posix()
GENERATED = ("<!-- Generated by build.py - edit the generator, not this file. -->",
             "<!-- Generated by build.py — edit the generator, not this file. -->")
COMMENT = (
    "<!-- EXPLORATION (Step 53A), not an approved design: Primer V2 Light\n"
    "     foundations, variant {variant}. Derived from ../../consolidation-pilot/{src},\n"
    "     which is only read. Generated by build.py; edit the generator, not this file. -->"
)

# page id -> pilot file relative to consolidation-pilot/ (no extension)
PAGES = {
    "home": "home/index",                       # navigation, editorial GP card, chips, inverse band, Winner tag
    "st-index": "standings/index",              # segmented selector, leader card
    "st-states": "standings/states",            # notices (stale, refresh failed), provisional marker
    "ex-cue": "explore/cue",                    # three-option selector, team-colour accents
    "gp-results": "grand-prix-detail/results",  # solid status chips, retained winner gradient
}
DARK = ["../dark-state-boundaries/candidate.css", "../dark-state-boundaries/refine-focus.css"]
VARIANTS = {
    "dark": DARK,
    "light-a": DARK + ["light-roles.css", "light-a.css"],
    "light-b": DARK + ["light-roles.css", "light-b.css"],
    # Step 53A.1: "B Motorsport", a refinement of B on three pages only.
    "light-bm": DARK + ["light-roles.css", "light-b.css", "light-bm.css"],
    # Step 53B: focus and team-colour corrections on the approved B Motorsport (LT-1).
    "light-53b": DARK + ["light-roles.css", "light-b.css", "light-bm.css", "light-53b.css"],
}
# variant -> pages (default: every page). Explore was added to light-bm in Step 53B
# as the same-structure "before" page (light-bm.css changes nothing on it).
ONLY = {
    "light-bm": ("home", "gp-results", "st-index", "ex-cue"),
    "light-53b": ("home", "gp-results", "st-index", "ex-cue"),
}


def sub(text: str, old: str, new: str, label: str) -> str:
    found = text.count(old)
    if found != 1:
        raise SystemExit(f"{label}: expected 1 match, found {found}: {old[:70]!r}")
    return text.replace(old, new)


def rebase(text: str, src_dir: str) -> str:
    """Rewrite each relative href/src so it resolves to the same file from HERE."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        if not url or url.startswith(("#", "http:", "https:", "data:", "mailto:", "/")):
            return m.group(0)
        cut = re.search(r"[?#]", url)
        path, tail = (url[:cut.start()], url[cut.start():]) if cut else (url, "")
        target = posixpath.normpath(posixpath.join(src_dir, path))
        return f'{attr}="{posixpath.relpath(target, HERE_REL)}{tail}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, text)


def derive(page_id: str, variant: str, lang: str) -> str:
    src = PAGES[page_id]
    name = f"{src}.html" if lang == "en" else f"{src}.es.html"
    path = PILOT / name
    s = path.read_text(encoding="utf-8")
    comment = COMMENT.format(variant=variant, src=name)
    generated = [g for g in GENERATED if g in s]
    if generated:
        s = sub(s, generated[0], comment, "comment")
    else:
        s = sub(s, "<body>\n", f"<body>\n{comment}\n", "comment")
    s = rebase(s, path.parent.relative_to(PRIMER).as_posix())
    s = re.sub(r"(?m)^[ \t]+$", "", s)   # whitespace-only lines render nothing
    links = "".join(f'<link rel="stylesheet" href="{c}">\n' for c in VARIANTS[variant])
    return sub(s, "</head>", f"{links}</head>", "stylesheets")


def outputs() -> dict[str, str]:
    out: dict[str, str] = {}
    for page_id in PAGES:
        for variant in VARIANTS:
            if page_id not in ONLY.get(variant, PAGES):
                continue
            for lang in ("en", "es"):
                out[f"{page_id}-{variant}{'' if lang == 'en' else '.es'}.html"] = derive(page_id, variant, lang)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
