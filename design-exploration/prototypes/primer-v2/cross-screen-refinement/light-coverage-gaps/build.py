"""Primer V2 Light coverage gaps (Step 54A). Python 3 stdlib only.

    python build.py           write the pages into this folder
    python build.py --check   verify the written pages are current (no write)

A visual prototype only: not a Flutter contract, not an accessibility
certification. It renders, in the frozen Light roles (LIGHT-THEME-ROLES.md,
LT-18), the five approved variants that LIGHT-READINESS.md section 11 found
rendered only in Dark experiment pages. Every page is derived from the
approved Dark experiment page, which is only read:

- HM-01  hm01        <- ../home-upcoming-omit/index (Home without the empty
                        "Upcoming events" section, Step 49B.1/49B.2)
- VS-1   gp-states   <- ../status-visual-consistency/gp-states (format,
                        session and finish unknown dashed: frames 8, 9, 22)
         cd-states   <- ../status-visual-consistency/cd-states (format
                        unknown dashed on Circuit, frame 13)
- VS-3   st-states   <- ../status-visual-consistency/st-states (Standings row
                        marker without the dagger, frame 8)
- VS-4 + N-2
         notices-combined-partial <- ../status-visual-consistency/
                        notices-proposed-combined-partial (N-2 wording with the
                        alert icon; help icon on the incomplete-profile notice)
         notices-stale <- ../status-visual-consistency/notices-proposed-stale
                        (clock icon)
         cal-n2      <- ../notice-coexistence/calendar (Calendar, N-2 wording
                        B, ?state=failed,stale&copy=b)

Two corrections bring a source page to its later approved state (the source
pages predate the decision; nothing new is designed):

- gp-states: the Step 49E page also carries the VS-2 dagger on "Provisional"
  (2 aria-hidden spans), which the owner rejected (VS-2). They are removed, so
  the "Provisional" chip is the pilot's again.
- cal-n2: the Step 49D.2 Calendar page marks the combined notice with
  cloud-off; VS-4 (Calendar included) replaced it with the alert icon. The
  combined notice B uses #i-alert, and the existing alert symbol is copied
  verbatim from the Driver Detail sprite (as Step 49E copied the clock).

Variants, from the same markup:

- "dark": the page plus the frozen Dark overlays (DK-1 to DK-3,
  ../dark-state-boundaries/candidate.css and refine-focus.css);
- "light": the dark chain plus the frozen Light chain, reused unchanged
  (LIGHT-THEME-ROLES.md "Sources"): ../light-foundations/ light-roles.css,
  light-b.css, light-bm.css, light-53b.css; ../light-rollout-b1/light-b1.css
  and lt14-a.css (LT-14); ../light-rollout-b2/light-b2.css (LT-17 included).

No stylesheet of its own: no new token, colour or rule. The derivation
otherwise changes exactly two things: relative href/src values are rebased so
they resolve to the same files as from the source, and the stylesheets above
are linked last. Words, data, accessible names and scripts are unchanged
(checks-gaps.mjs verifies it against the source pages in the browser).
"""

from __future__ import annotations

import posixpath
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
PRIMER = HERE.parent.parent
HERE_REL = HERE.relative_to(PRIMER).as_posix()
CSR = "cross-screen-refinement"
COMMENT = (
    "<!-- VISUAL PROTOTYPE (Step 54A, Light coverage gaps), variant {variant}.\n"
    "     Derived from ../../{src}, which is only read{fix}. Not a Flutter\n"
    "     contract. Generated by build.py; edit the generator, not this file. -->"
)

# page id -> (source page relative to primer-v2/, without extension; correction)
PAGES = {
    "hm01": (f"{CSR}/home-upcoming-omit/index", None),
    "gp-states": (f"{CSR}/status-visual-consistency/gp-states", "no-dagger"),
    "cd-states": (f"{CSR}/status-visual-consistency/cd-states", None),
    "st-states": (f"{CSR}/status-visual-consistency/st-states", None),
    "notices-combined-partial": (f"{CSR}/status-visual-consistency/notices-proposed-combined-partial", None),
    "notices-stale": (f"{CSR}/status-visual-consistency/notices-proposed-stale", None),
    "cal-n2": (f"{CSR}/notice-coexistence/calendar", "alert-icon"),
}
FIX_NOTE = {
    "no-dagger": ";\n     the rejected VS-2 dagger (2 aria-hidden spans) removed",
    "alert-icon": ";\n     combined notice B marked with the VS-4 alert icon",
}
DARK = ["../dark-state-boundaries/candidate.css", "../dark-state-boundaries/refine-focus.css"]
LIGHT = DARK + ["../light-foundations/light-roles.css", "../light-foundations/light-b.css",
                "../light-foundations/light-bm.css", "../light-foundations/light-53b.css",
                "../light-rollout-b1/light-b1.css", "../light-rollout-b1/lt14-a.css",
                "../light-rollout-b2/light-b2.css"]
VARIANTS = {"dark": DARK, "light": LIGHT}

DAGGER = '<span class="dagger" aria-hidden="true">†</span>'
CLOUD_OFF_SYMBOL = re.compile(r'(  <symbol id="i-cloud-off" [^\n]*</symbol>\n)')
ALERT_SYMBOL = ('  <symbol id="i-alert" viewBox="0 0 24 24"><circle cx="12" cy="12" r="10"/>'
                '<path d="M12 8v4"/><path d="M12 16h.01"/></symbol>\n')
COMBINED_B = '<p class="notice" role="status" data-state="combined-b" hidden><svg class="icon" aria-hidden="true"><use href="#i-cloud-off"/>'


def sub(text: str, old: str, new: str, label: str, count: int = 1) -> str:
    found = text.count(old)
    if found != count:
        raise SystemExit(f"{label}: expected {count} match(es), found {found}: {old[:70]!r}")
    return text.replace(old, new)


def rebase(text: str, src_dir: str) -> str:
    """Rewrite each relative href/src so it resolves to the same file from HERE."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        if not url or url.startswith(("#", "http:", "https:", "data:", "mailto:", "/")):
            return m.group(0)
        cut = re.search(r"[?#]", url)
        path, tail = (url[:cut.start()], url[cut.start():]) if cut else (url, "")
        target = posixpath.normpath(posixpath.join(src_dir, path))
        return f'{attr}="{posixpath.relpath(target, HERE_REL)}{tail}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, text)


def correct(s: str, fix: str | None) -> str:
    if fix == "no-dagger":
        return sub(s, DAGGER, "", "VS-2 dagger", count=2)
    if fix == "alert-icon":
        driver_sprite = (PRIMER / "consolidation-pilot" / "driver-detail" / "index.html").read_text(encoding="utf-8")
        assert ALERT_SYMBOL in driver_sprite, "alert symbol must be the existing one, verbatim"
        assert "i-alert" not in s
        s = CLOUD_OFF_SYMBOL.sub(lambda m: m.group(1) + ALERT_SYMBOL, s)
        assert s.count(ALERT_SYMBOL) == 1, "alert symbol inserted once"
        return sub(s, COMBINED_B, COMBINED_B.replace("#i-cloud-off", "#i-alert"), "combined-b icon")
    return s


def derive(page_id: str, variant: str, lang: str) -> str:
    src, fix = PAGES[page_id]
    name = f"{src}.html" if lang == "en" else f"{src}.es.html"
    path = PRIMER / name
    s = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    s = correct(s, fix)
    body = re.findall(r"<body[^>]*>\n", s)
    assert len(body) == 1, (name, body)
    comment = COMMENT.format(variant=variant, src=name, fix=FIX_NOTE.get(fix, ""))
    s = s.replace(body[0], f"{body[0]}{comment}\n", 1)
    s = rebase(s, path.parent.relative_to(PRIMER).as_posix())
    s = re.sub(r"(?m)^[ \t]+$", "", s)   # whitespace-only lines render nothing
    links = "".join(f'<link rel="stylesheet" href="{c}">\n' for c in VARIANTS[variant])
    return sub(s, "</head>", f"{links}</head>", "stylesheets")


def outputs() -> dict[str, str]:
    return {f"{page_id}-{variant}{'' if lang == 'en' else '.es'}.html": derive(page_id, variant, lang)
            for page_id in PAGES for variant in VARIANTS for lang in ("en", "es")}


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
