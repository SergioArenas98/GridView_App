"""Circuit Detail event-absence EXPERIMENT (Step 49B.1). Python 3 stdlib only.

    python build.py           write the experiment files into this folder
    python build.py --check   verify the written files are current (no write)

Development-only. Not an approved design, not a fixture, not a Flutter
contract. Every file is derived from the Circuit Detail consolidation pilot
(../../consolidation-pilot/circuit-detail/, pixel-identical to the approved
../../circuit-detail/), which is only read, never written.

Accepted direction (STATUS-ABSENCE-DECISIONS.md section 1, CIR-02):

- linked event known                         -> index[.es].html, unchanged
- no event, season calendar materialized     -> no-event[.es].html, unchanged
  (confirmed absence: "No Grand Prix this season" may be shown)
- no event, calendar completeness not
  established                                -> unknown-association[.es].html
  (same fixture as no-event; the related-Grand Prix block is omitted)
- the partial profile (Scenario B) under the
  same unknown condition                     -> partial-unknown[.es].html
  (same fixture as partial; the block is omitted)

The calendar's materialization is not visible in the fixtures; it is the
development-only condition each page names in its comment and description.
No copy is added or changed; every other block is untouched.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent.parent / "consolidation-pilot" / "circuit-detail"

MAIN_OPEN = '<main class="page">\n'
REL_BLOCK = re.compile(r'<section class="sec rel" aria-labelledby="m-rel">\n.*?</section>\n', re.S)
STATES = {
    "index": "linked event known (unchanged copy of the pilot)",
    "no-event": "no linked event and the season calendar confirmed complete "
                "(materialized); unchanged copy of the pilot",
    "unknown-association": "no linked event and the season calendar's completeness "
                           "not established; the unsupported absence statement is omitted",
    "partial-unknown": "Scenario B (partial profile) with the season calendar's completeness "
                       "not established; the unsupported absence statement is omitted",
}
DERIVED = {"index": "index", "no-event": "no-event", "unknown-association": "no-event", "partial-unknown": "partial"}


def read(name: str) -> str:
    return (SOURCE / name).read_text(encoding="utf-8").replace("\r\n", "\n")


def comment(state: str, source: str) -> str:
    return (
        "<!-- EXPERIMENT (Step 49B.1), development-only state, not an approved design:\n"
        f"     {STATES[state]}.\n"
        f"     Derived from ../../consolidation-pilot/circuit-detail/{source}. Generated by\n"
        "     build.py; edit the generator, not this file. -->\n"
    )


def page(state: str, sfx: str) -> str:
    source = f"{DERIVED[state]}{sfx}.html"
    html = read(source)
    if state in ("unknown-association", "partial-unknown"):
        blocks = REL_BLOCK.findall(html)
        assert len(blocks) == 1 and 'class="rel__none"' in blocks[0] and "a class=\"rx\"" not in blocks[0], source
        html = REL_BLOCK.sub("", html)
        desc = re.search(r'<meta name="description" content="([^"]*)">', html)
        assert desc, source
        label = "development-only state: season calendar completeness not established, related Grand Prix block omitted"
        html = html.replace(desc.group(0), f'<meta name="description" content="{desc.group(1)} Step 49B.1 {label}.">')
    assert html.count(MAIN_OPEN) == 1, source
    return html.replace(MAIN_OPEN, comment(state, source) + MAIN_OPEN)


def outputs() -> dict[str, str]:
    out: dict[str, str] = {}
    for state in STATES:
        for sfx in ("", ".es"):
            out[f"{state}{sfx}.html"] = page(state, sfx)
    out["cd.css"] = read("cd.css")
    return out


def main() -> None:
    check_only = "--check" in sys.argv
    stale = []
    for name, text in outputs().items():
        target = HERE / name
        current = target.exists() and target.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        if check_only:
            print(f"{'ok ' if current else 'STALE'} {name}")
            if not current:
                stale.append(name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    if check_only:
        assert not stale, f"stale: {stale}"
    else:
        print("wrote", ", ".join(outputs()))


if __name__ == "__main__":
    main()
