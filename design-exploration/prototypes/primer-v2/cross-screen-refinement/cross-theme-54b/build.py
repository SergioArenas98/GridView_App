"""Primer V2 cross-theme consolidation experiments (Step 54B). Python 3 stdlib only.

    python build.py           write the pages into this folder
    python build.py --check   verify the written pages are current (no write)

EXPERIMENT, not an approved design and not a Flutter contract. Three
isolated comparisons for CROSS-THEME-CONSOLIDATION.md; every source page is
only read:

- A. Home Explore focus (XS-31): home <- ../home-upcoming-omit/index (HM-01,
  the authoritative Home). Variants dark / light (frozen chains, ring 3px
  outside the link, clipped by the strip) and dark-inset / light-inset
  (explore-focus.css: the same ring drawn inside the link).
- B. Calendar completed row (XS-11, CAL-01): cal <- ../light-rollout-b1/
  lt14-dark (the established LT-14 comparison fixture: Calendar Stage 1 plus
  the round 12 completed row; frozen Dark chain already linked). One variant,
  dark-full: the same page plus ../light-rollout-b1/lt14-a.css, the exact
  LT-14 rule (.ev--completed .ev__link { opacity: 1 }), reused unchanged.
  The current Dark (lt14-dark) and Light (lt14-light-a) pages are compared
  in place.
- C. Team-colour seams (XS-25): ex-cue <- ../../consolidation-pilot/explore/
  cue (ticks) and td-states <- ../../consolidation-pilot/team-detail/states
  (frames 10 #1E41FF and 11 #FF8000: banner rail and line-up seam). Variants
  dark / light (frozen chains, today's geometry) and dark-seam / light-seam
  (seam-dark.css / seam-light.css: one shared edge geometry).

Chains: "dark" = the frozen Dark overlays (DK-1 to DK-3); "light" = the
frozen Light chain (LIGHT-THEME-ROLES.md "Sources", as in
../light-coverage-gaps/). The derivation changes only relative href/src
values (rebased) and appends stylesheets; markup, words, data, accessible
names and scripts are unchanged (checks-54b.mjs verifies it).
"""

from __future__ import annotations

import posixpath
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
PRIMER = HERE.parent.parent
HERE_REL = HERE.relative_to(PRIMER).as_posix()
COMMENT = (
    "<!-- EXPERIMENT (Step 54B, cross-theme consolidation), page {page}, variant\n"
    "     {variant}. Derived from ../../{src}, which is only read. Not an approved\n"
    "     design. Generated by build.py; edit the generator, not this file. -->"
)

DARK = ["../dark-state-boundaries/candidate.css", "../dark-state-boundaries/refine-focus.css"]
LIGHT = DARK + ["../light-foundations/light-roles.css", "../light-foundations/light-b.css",
                "../light-foundations/light-bm.css", "../light-foundations/light-53b.css",
                "../light-rollout-b1/light-b1.css", "../light-rollout-b1/lt14-a.css",
                "../light-rollout-b2/light-b2.css"]

# page id -> (source relative to primer-v2/, without extension; {variant: stylesheets appended})
PAGES = {
    "home": ("cross-screen-refinement/home-upcoming-omit/index",
             {"dark": DARK, "light": LIGHT,
              "dark-inset": DARK + ["explore-focus.css"], "light-inset": LIGHT + ["explore-focus.css"]}),
    "cal": ("cross-screen-refinement/light-rollout-b1/lt14-dark",
            {"dark-full": ["../light-rollout-b1/lt14-a.css"]}),
    "ex-cue": ("consolidation-pilot/explore/cue",
               {"dark": DARK, "light": LIGHT,
                "dark-seam": DARK + ["seam-dark.css"], "light-seam": LIGHT + ["seam-light.css"]}),
    "td-states": ("consolidation-pilot/team-detail/states",
                  {"dark": DARK, "light": LIGHT,
                   "dark-seam": DARK + ["seam-dark.css"], "light-seam": LIGHT + ["seam-light.css"]}),
}


def sub(text: str, old: str, new: str, label: str) -> str:
    found = text.count(old)
    if found != 1:
        raise SystemExit(f"{label}: expected 1 match, found {found}: {old[:70]!r}")
    return text.replace(old, new)


def rebase(text: str, src_dir: str) -> str:
    """Rewrite each relative href/src so it resolves to the same file from HERE."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        if not url or url.startswith(("#", "http:", "https:", "data:", "mailto:", "/")):
            return m.group(0)
        cut = re.search(r"[?#]", url)
        path, tail = (url[:cut.start()], url[cut.start():]) if cut else (url, "")
        target = posixpath.normpath(posixpath.join(src_dir, path))
        return f'{attr}="{posixpath.relpath(target, HERE_REL)}{tail}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, text)


def derive(page_id: str, variant: str, lang: str) -> str:
    src, variants = PAGES[page_id]
    name = f"{src}.html" if lang == "en" else f"{src}.es.html"
    path = PRIMER / name
    s = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    body = re.findall(r"<body[^>]*>\n", s)
    assert len(body) == 1, (name, body)
    s = s.replace(body[0], f"{body[0]}{COMMENT.format(page=page_id, variant=variant, src=name)}\n", 1)
    s = rebase(s, path.parent.relative_to(PRIMER).as_posix())
    s = re.sub(r"(?m)^[ \t]+$", "", s)   # whitespace-only lines render nothing
    links = "".join(f'<link rel="stylesheet" href="{c}">\n' for c in variants[variant])
    return sub(s, "</head>", f"{links}</head>", "stylesheets")


def outputs() -> dict[str, str]:
    return {f"{page_id}-{variant}{'' if lang == 'en' else '.es'}.html": derive(page_id, variant, lang)
            for page_id, (_, variants) in PAGES.items() for variant in variants for lang in ("en", "es")}


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
