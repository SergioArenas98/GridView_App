"""Dark state-boundaries EXPERIMENT (Step 51C). Python 3 stdlib only.

    python build.py           write the experiment pages into this folder
    python build.py --check   verify the written pages are current (no write)

Not an approved design, not a fixture, not a Flutter contract. Every page is a
consolidation-pilot page (each pixel-identical to its approved prototype),
which is only read. The derivation changes exactly two things (plus, since
Step 52B, the spaces on whitespace-only lines, which render nothing):
- every relative href/src is rebased so it resolves to the same file as from
  the pilot (stylesheets, scripts and links stay the pilots' own);
- one or two stylesheets are linked last: candidate.css (A1 outline, A2 flat
  oxide, A3 Chalk focus ring) and, for the "-mark" pages only,
  candidate-mark.css (the A2 structural selected cue).
Markup, words, data, accessible names and scripts are unchanged.

Step 51C.1 pages ("-refine") add refine-focus.css (and refine-cue.css) on
top of candidate.css; their reference is the matching 51C "-candidate" page.

Step 51D adds home-candidate (candidate.css only) to measure the existing Home
championship-band focus ring; checks-51d.mjs compares it with the pilot page.

The "current" reference is the pilot page itself. checks.mjs compares each
pilot page with its candidate page, and with the candidate stylesheets
switched off (control: must be identical to the pilot).
"""

from __future__ import annotations

import posixpath
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
PRIMER = HERE.parent.parent
PILOT = PRIMER / "consolidation-pilot"
HERE_REL = HERE.relative_to(PRIMER).as_posix()
GENERATED = ("<!-- Generated by build.py - edit the generator, not this file. -->",
             "<!-- Generated by build.py — edit the generator, not this file. -->")
COMMENT = (
    "<!-- EXPERIMENT (Step 51C), not an approved design: dark state boundaries\n"
    "     ({what}). Derived from ../../consolidation-pilot/{src}, which is only\n"
    "     read. Generated by build.py; edit the generator, not this file. -->"
)

# page id -> (pilot file relative to consolidation-pilot/, what, extra stylesheets)
PAGES = {
    "gp-results-candidate": ("grand-prix-detail/results", "A1 outline", ["candidate.css"]),
    "gp-states-candidate": ("grand-prix-detail/states", "A1 outline", ["candidate.css"]),
    "st-index-candidate": ("standings/index", "A1, A2 flat oxide, A3", ["candidate.css"]),
    "st-index-candidate-mark": ("standings/index", "A1, A2 flat oxide + selected cue, A3",
                                ["candidate.css", "candidate-mark.css"]),
    "st-states-candidate": ("standings/states", "A1 inverse outline", ["candidate.css"]),
    "cal-index-candidate": ("index", "A1, A2 flat oxide, A3", ["candidate.css"]),
    # Step 51C.1: on top of the approved 51C candidate (A1, flat oxide, Chalk ring on oxide).
    "st-index-refine": ("standings/index", "51C.1: flat slab, Chalk ring on every selector option",
                        ["candidate.css", "refine-focus.css"]),
    "st-index-refine-cue": ("standings/index", "51C.1: flat slab + 12-degree cue, Chalk ring on every option",
                            ["candidate.css", "refine-focus.css", "refine-cue.css"]),
    "cal-index-refine": ("index", "51C.1: next-event ring above the oxide block",
                         ["candidate.css", "refine-focus.css"]),
    "gp-results-refine": ("grand-prix-detail/results", "51C.1: row ring above the rail cell",
                          ["candidate.css", "refine-focus.css"]),
    # Step 51D: measurement only (Home championship-band ring under the approved A1 / flat oxide).
    "home-candidate": ("home/index", "51D: Home championship-band focus measurement, approved A1",
                       ["candidate.css"]),
}


def sub(text: str, old: str, new: str, label: str) -> str:
    found = text.count(old)
    if found != 1:
        raise SystemExit(f"{label}: expected 1 match, found {found}: {old[:70]!r}")
    return text.replace(old, new)


def rebase(text: str, src_dir: str) -> str:
    """Rewrite each relative href/src so it resolves to the same file from HERE."""
    def fix(m: re.Match[str]) -> str:
        attr, url = m.group(1), m.group(2)
        if not url or url.startswith(("#", "http:", "https:", "data:", "mailto:", "/")):
            return m.group(0)
        cut = re.search(r"[?#]", url)
        path, tail = (url[:cut.start()], url[cut.start():]) if cut else (url, "")
        target = posixpath.normpath(posixpath.join(src_dir, path))
        new = posixpath.relpath(target, HERE_REL) + tail
        return f'{attr}="{new}"'
    return re.sub(r'\b(href|src)="([^"]*)"', fix, text)


def derive(page_id: str, lang: str) -> str:
    src, what, sheets = PAGES[page_id]
    name = f"{src}.html" if lang == "en" else f"{src}.es.html"
    path = PILOT / name
    s = path.read_text(encoding="utf-8")
    src_dir = path.parent.relative_to(PRIMER).as_posix()
    comment = COMMENT.format(what=what, src=name)
    generated = [g for g in GENERATED if g in s]
    if generated:
        s = sub(s, generated[0], comment, "comment")
    else:  # the Calendar pilot pages carry no generated-file comment
        s = sub(s, "<body>\n", f"<body>\n{comment}\n", "comment")
    s = rebase(s, src_dir)
    links = "".join(f'<link rel="stylesheet" href="{c}">\n' for c in sheets)
    # Step 52B: drop the spaces on whitespace-only lines (one inherited from the
    # GP states pilot); inter-element whitespace, so rendering is unchanged.
    s = re.sub(r"(?m)^[ \t]+$", "", s)
    return sub(s, "</head>", f"{links}</head>", "stylesheets")


def outputs() -> dict[str, str]:
    out: dict[str, str] = {}
    for page_id in PAGES:
        for lang in ("en", "es"):
            out[f"{page_id}{'' if lang == 'en' else '.es'}.html"] = derive(page_id, lang)
    return out


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        print("current" if not stale else "stale: " + ", ".join(stale))
        return 1 if stale else 0
    print(f"wrote {len(outputs())} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
