"""Calendar title-fit EXPERIMENT (Step 48B). Python 3 stdlib only.

    python build.py           write the experiment files into this folder
    python build.py --check   verify the written files are current (no write)

Not an approved design, not a fixture, not a Flutter contract. It evaluates
one change: Calendar's `14cqi` title cap replaced by the shared title fit
(rule S-2: width axis 118 -> 100 -> 84 -> 72, then a last-resort scale), the
rule Standings and Explore already use.

Every file is derived from the pixel-identical Calendar consolidation pilot
(../../consolidation-pilot/), which is only read, never written. Each change is
a single asserted text substitution, so markup, data, copy, localization,
navigation and state behaviour stay the pilot's (= the approved Calendar's):

- index[.es].html: the experiment comment; shared paths one level deeper; the
  shared title-fit script plus a three-line driver; the Home tab link one
  level deeper (same target). The <title> is unchanged (it names the
  accessibility tree's root and would make the trees differ).
- calendar.css: the two `14cqi` rules replaced by Standings' four title-fit
  rules, re-scoped from `.appbar--pinned` to `.appbar--sticky`.
- calendar-states.js: copied verbatim.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
PILOT = HERE.parent.parent / "consolidation-pilot"

PILOT_COMMENT = (
    "<!-- Consolidation pilot: same markup as ../calendar/{name}; only the\n"
    "     stylesheet and script links differ (shared foundation in ../shared/). -->"
)
EXPERIMENT_COMMENT = (
    "<!-- EXPERIMENT (Step 48B), not an approved design: Calendar title fit.\n"
    "     Same markup as ../../consolidation-pilot/{name} (= the approved\n"
    "     ../../calendar/{name}); only the stylesheet and script links differ.\n"
    "     Generated by build.py; edit the generator, not this file. -->"
)
SCRIPTS_OLD = '<script src="../shared/nav-inset.js" defer></script>'
SCRIPTS_NEW = (
    '<script src="../../shared/nav-inset.js" defer></script>\n'
    '<script src="../../shared/title-fit.js" defer></script>\n'
    '<script src="calendar-title.js" defer></script>'
)

CSS_OLD = """/* A screen title is one word that cannot wrap ("Calendario"). Besides the
   wordmark's cap, it is also limited by its own column (≈6.8em per word at
   wdth 118), so at 320dp + 200% it stops short of the actions. */
.appbar--sticky .appbar__brand { container-type: inline-size; }
.appbar--sticky .wordmark { font-size: min(1.5rem, 34px, 14cqi); }
"""
CSS_NEW = """/* EXPERIMENT (Step 48B): the `14cqi` cap is replaced by the shared title fit
   (../../shared/title-fit.js, rule S-2), with Standings' four rules
   (standings.css, `.appbar--pinned`) re-scoped to this sticky bar. The title
   keeps the shared wordmark size, min(1.5rem, 34px); calendar-title.js narrows
   the width axis (118 → 100 → 84 → 72) and scales only a word that still
   overflows its column. */
.appbar--sticky .appbar__brand { min-width: 0; }
.appbar--sticky .wordmark { max-width: 100%; white-space: nowrap; }
.appbar--sticky .wordmark[data-fit="w100"] { font-variation-settings: "wdth" 100; }
.appbar--sticky .wordmark[data-fit="w84"] { font-variation-settings: "wdth" 84; }
.appbar--sticky .wordmark[data-fit="w72"], .appbar--sticky .wordmark[data-fit="scaled"] { font-variation-settings: "wdth" 72; }
"""
CSS_HEADER_OLD = "/* GridView — Primer V2: Calendar, CONSOLIDATION PILOT copy of"
CSS_HEADER_NEW = (
    "/* EXPERIMENT (Step 48B), generated by build.py from\n"
    "   ../../consolidation-pilot/calendar.css; the only rule change is the\n"
    "   title-fit block below. Not an approved design. Pilot header follows.\n\n"
    "   GridView — Primer V2: Calendar, CONSOLIDATION PILOT copy of"
)

DRIVER = """// EXPERIMENT (Step 48B). Calendar's title uses the shared title fit
// (../../shared/title-fit.js) with its own triggers, as Standings' layout pass
// has: Calendar has no header budget, so nothing is measured after the fit.
(() => {
  const title = document.querySelector('.appbar--sticky .wordmark');
  if (title && window.GvTitleFit) window.GvTitleFit.attach(title);
})();
"""


def swap(text: str, old: str, new: str, count: int = 1) -> str:
    found = text.count(old)
    assert found == count, (old[:60], found, count)
    return text.replace(old, new)


def read(name: str) -> str:
    return (PILOT / name).read_text(encoding="utf-8").replace("\r\n", "\n")


def page(name: str, home: str) -> str:
    html = read(name)
    html = swap(html, PILOT_COMMENT.format(name=name), EXPERIMENT_COMMENT.format(name=name))
    html = swap(html, 'href="../shared/', 'href="../../shared/', count=6)
    html = swap(html, SCRIPTS_OLD, SCRIPTS_NEW)
    html = swap(html, f'href="../refinement-01/{home}"', f'href="../../refinement-01/{home}"')
    return html


def outputs() -> dict[str, str]:
    css = swap(read("calendar.css"), CSS_OLD, CSS_NEW)
    css = swap(css, CSS_HEADER_OLD, CSS_HEADER_NEW)
    return {
        "index.html": page("index.html", "index.html"),
        "index.es.html": page("index.es.html", "index.es.html"),
        "calendar.css": css,
        "calendar-states.js": read("calendar-states.js"),
        "calendar-title.js": DRIVER,
    }


def main() -> None:
    check_only = "--check" in sys.argv
    stale = []
    for name, text in outputs().items():
        target = HERE / name
        current = target.exists() and target.read_text(encoding="utf-8").replace("\r\n", "\n") == text
        if check_only:
            print(f"{'ok ' if current else 'STALE'} {name}")
            if not current:
                stale.append(name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
    if check_only:
        assert not stale, f"stale: {stale}"
    else:
        print("wrote", ", ".join(outputs()))


if __name__ == "__main__":
    main()
