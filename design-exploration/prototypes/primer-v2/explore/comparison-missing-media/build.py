ICON = {"drivers": "i-driver", "teams": "i-shield", "circuits": "i-circuit"}


def slot(state: str, icon: str) -> str:
    inner = f'<svg class="icon" aria-hidden="true"><use href="#{icon}"/></svg>' if state == "failed" else ""
    return f'<span class="ent__media ent__media--{state}" data-state="{state}">{inner}</span>'


def mixed_list(t: dict, states: tuple[str, ...], lid: str, interactive: bool = False) -> str:
    rows = []
    for d, state in zip(base.DRIVERS, states):
        row = base.driver_row(d, t)
        row = re.sub(r'<span class="ent__media">.*?</span>', slot(state, ICON["drivers"]), row, count=1)
        rows.append(row)
    attrs = ' data-interactive="true"' if interactive else ""
    return (f'  <ol class="lib lib--media" id="{lid}" aria-labelledby="{lid}-t"{attrs}>\n'
            + "\n".join(rows) + "\n  </ol>")


def states_page(t: dict, lang: str) -> str:
    g = G[lang]
    sfx = "" if lang == "en" else ".es"
    out = rebase(base.head(t, f"GridView {g['title']}", f"{g['flag']}.", extra_css="../states.css"))
