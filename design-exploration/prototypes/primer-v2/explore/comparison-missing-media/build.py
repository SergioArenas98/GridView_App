"""Generates the Explore missing-media comparison pages (Python 3 stdlib only).

    python build.py

The approved baseline (../index.html, generated by ../build.py) is NOT
modified. This generator *imports* ../build.py read-only and reuses its own
page and row output, so fixture data, row order, copy, accessible labels,
links, the category selector and its scroll restoration are the baseline's by
construction. Only the presentation changes:

- index[.es].html         Alternative A: a collection with no media
                          reference renders no image column at all.
- cue[.es].html           Alternative B: A plus a quiet row-navigation cue
                          (kept separate, so the two variables can be judged
                          apart).
- media-states[.es].html  Development-only gallery: how A coexists with media
                          (no reference / loading / failed / loaded) without
                          layout shift. Geometry only: no image exists or is
                          drawn.

Stylesheets and scripts are the baseline's (../primer-core.css,
../explore.css, ../nav-inset.js, ../explore.js), plus comparison.css and,
for the gallery only, media-states.js.
"""

from __future__ import annotations

import importlib.util
import re
import sys

sys.dont_write_bytecode = True        # importing ../build.py must leave nothing in ../
from html import escape
from pathlib import Path

HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("explore_baseline", HERE.parent / "build.py")
base = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = base         # dataclasses resolve their module here
_spec.loader.exec_module(base)          # read-only: main() is not called

MEDIA_SPAN = re.compile(r'\n\s*<span class="ent__media"><svg class="icon" aria-hidden="true"><use href="#i-[a-z]+"/></svg></span>')
CUE = ('\n        <svg class="icon ent__go" aria-hidden="true" focusable="false"><use href="#i-chevron"/></svg>')
CHEVRON_SYMBOL = '  <symbol id="i-chevron" viewBox="0 0 24 24"><path d="m9 18 6-6-6-6"/></symbol>\n</svg>'

VARIANTS = {
    "a": {"stem": "index", "title": "Alternative A: no placeholder tiles", "cue": False},
    "b": {"stem": "cue", "title": "Alternative B: no placeholder tiles + row cue", "cue": True},
}


def rebase(html: str) -> str:
    """Point the baseline's relative asset and navigation paths one level up."""
    html = html.replace('href="primer-core.css"', 'href="../primer-core.css"')
    html = html.replace('href="explore.css">', 'href="../explore.css">\n<link rel="stylesheet" href="comparison.css">')
    html = html.replace('src="nav-inset.js"', 'src="../nav-inset.js"').replace('src="explore.js"', 'src="../explore.js"')
    html = html.replace('href="../refinement-01/', 'href="../../refinement-01/')
    html = html.replace('href="../calendar/', 'href="../../calendar/').replace('href="../standings/', 'href="../../standings/')
    return html


def strip_media(html: str) -> str:
    out, n = MEDIA_SPAN.subn("", html)
    assert n == len(base.DRIVERS) + len(base.TEAMS) + len(base.CIRCUITS), n
    return out.replace('<ol class="lib"', '<ol class="lib lib--nomedia"')


def add_cue(html: str) -> str:
    out, n = re.subn(r'(\n      </a>\n    </li>)', CUE + r'\1', html)
    assert n == len(base.DRIVERS) + len(base.TEAMS) + len(base.CIRCUITS), n
    return out.replace('<ol class="lib lib--nomedia"', '<ol class="lib lib--nomedia lib--cue"')


def variant_page(t: dict, key: str) -> str:
    v = VARIANTS[key]
    html = rebase(base.index_page(t))
    html = strip_media(html)
    if v["cue"]:
        html = html.replace("</svg>\n", CHEVRON_SYMBOL + "\n", 1)
        html = add_cue(html)
    language = "English" if t["lang"] == "en" else "Spanish"
    html = re.sub(r'<meta name="description" content="[^"]*">',
                  f'<meta name="description" content="GridView Explore, Primer V2 comparison ({language}): {escape(v["title"])}. '
                  f'Same development fixtures as ../index.html; the approved baseline is unchanged.">', html, count=1)
    html = html.replace("<!-- Generated by build.py — edit the generator, not this file. -->",
                        f"<!-- Generated by comparison-missing-media/build.py from ../build.py (baseline unchanged). {v['title']}. -->")
    return html


