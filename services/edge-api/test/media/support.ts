/// A synthetic test master: flat colour bands on a solid ground.
///
/// **Generated, never copied.** Nothing in this repository's test data is a
/// driver photograph, a team logo, a Formula 1 mark or circuit photography, and
/// nothing here comes from a provider URL. These images are unmistakably
/// artificial geometry, which is all a processing test needs and the only thing
/// GridView has the right to use.
export async function syntheticMaster(
  width: number,
  height: number,
  options: { readonly alpha?: boolean } = {},
): Promise<Buffer> {
  const channels = options.alpha === true ? 4 : 3;
  const band = Math.max(1, Math.floor(height / 4));
  const pixels = Buffer.alloc(width * height * channels);
  for (let y = 0; y < height; y++) {
    const shade = ((Math.floor(y / band) + 1) * 48) % 256;
    for (let x = 0; x < width; x++) {
      const offset = (y * width + x) * channels;
      pixels[offset] = shade;
      pixels[offset + 1] = (x * 3) % 256;
      pixels[offset + 2] = 128;
      if (channels === 4) pixels[offset + 3] = 255;
    }
  }
  return sharp(pixels, { raw: { width, height, channels } }).png().toBuffer();
}

/// A synthetic master carrying an EXIF orientation flag, for the rotation test.
export async function rotatedSyntheticMaster(
  width: number,
  height: number,
): Promise<Buffer> {
  return sharp(await syntheticMaster(width, height))
    .withMetadata({ orientation: 6 })
    .jpeg()
    .toBuffer();
}

