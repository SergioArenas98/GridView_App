/// An in-memory object store, so publication is exercised end to end with no
/// bucket, no credential and no network.
export class FakeObjectStore {
  readonly objects = new Map<string, { contentHash: string; bytes: Buffer }>();
  readonly puts: string[] = [];

  async head(objectKey: string): Promise<{ contentHash: string } | null> {
    const existing = this.objects.get(objectKey);
    return existing ? { contentHash: existing.contentHash } : null;
  }

  async put(objectKey: string, bytes: Buffer): Promise<void> {
    this.puts.push(objectKey);
    const { createHash } = await import('node:crypto');
    this.objects.set(objectKey, {
      contentHash: createHash('sha256').update(bytes).digest('hex'),
      bytes,
    });
  }

  /// Seeds a key with content that differs from anything the pipeline produces,
  /// so an overwrite attempt is a genuine conflict.
  seedConflicting(objectKey: string): void {
    this.objects.set(objectKey, {
      contentHash: 'conflicting-content-hash',
      bytes: Buffer.from('different'),
    });
  }
}

