// Offline generation only: Workers execute static validators, never Ajv codegen.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import Ajv from 'ajv/dist/2020.js';
import formats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import spec from '../../src/identity/catalog/source-spec.json' with { type: 'json' };
const schemas = resolve(import.meta.dirname, '../../../../content/schemas');
const ajv = new Ajv({
  allErrors: true,
  strict: false,
  code: { source: true, esm: false },
});
formats(ajv);
for (const file of readdirSync(schemas).filter((p) =>
  p.endsWith('.schema.json'),
))
  ajv.addSchema(JSON.parse(readFileSync(resolve(schemas, file), 'utf8')));
const exports = Object.fromEntries(
  Object.values(spec).map((kind) => [
    kind.replaceAll('-', '_'),
    'https://gridview.local/schemas/' + kind + '.schema.json',
  ]),
);
const output =
  '/* eslint-disable */\n// Generated by scripts/identity/compile-schemas.mjs; do not edit.\n' +
  standalone(ajv, exports) +
  '\n';
const target = resolve(
  import.meta.dirname,
  '../../src/identity/catalog/content-schemas.cjs',
);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output)
    throw Error('Stale generated catalog schemas');
} else writeFileSync(target, output);
