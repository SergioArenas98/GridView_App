/// Visual coverage for Phase 8B media.
///
/// Deliberately **representative, not exhaustive**: a loaded state, a fallback
/// state and a failure state in each theme is enough to catch a regression in
/// how media sits in a layout. Every possible combination of slot, category and
/// outcome would multiply the baseline count without multiplying what the images
/// actually tell a reviewer.
///
/// Everything that could make an image non-deterministic is pinned: locale,
/// theme, platform brightness, surface size, text scale, clock, device time
/// zone, preferences, **loader state and cache state**. The loader serves every
/// request straight from its cache, so no fade animation is ever captured
/// mid-flight and no frame depends on timing.
///
/// The imagery is generated by `synthetic_png.dart` — flat geometric bands. It is
/// not a driver photograph, a team logo, a Formula 1 mark or circuit
/// photography, because GridView has the right to use none of those.
const Size _device = Size(390, 844);
final DateTime _clock = DateTime.utc(2026, 7, 18, 12, 10);

late Directory _tmp;
late File _square;
late File _wide;

/// Serves every request from cache, so a golden never captures a fade.
class _CachedLoader implements MediaImageLoader {
  _CachedLoader(this.file);

  final File file;

  @override
  Future<File?> cached(MediaImageRequest request) async => file;

  @override
  Future<MediaLoadOutcome> load(MediaImageRequest request) async =>
      MediaLoaded(file: file, fromCache: true);
}

/// Fails every request, so a golden captures the fallback rather than an image.
class _FailingLoader implements MediaImageLoader {
  @override
  Future<File?> cached(MediaImageRequest request) async => null;

  @override
  Future<MediaLoadOutcome> load(MediaImageRequest request) async =>
      const MediaLoadFailed(MediaFailureKind.network);
}

