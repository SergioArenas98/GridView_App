/// Lets every rendered image finish decoding before the frame is captured.
///
/// `Image.file` reads from disk and decodes asynchronously, which a widget
/// test's fake async never completes on its own. Without this a golden would
/// capture the placeholder and silently pass as though it were the loaded state
/// — the worst kind of green.
///
/// Each rendered `Image`'s own provider is resolved and awaited, rather than
/// waiting a fixed interval or calling `precacheImage`. A fixed delay does not
/// actually guarantee the frame arrived — it produced goldens showing an empty
/// slot, which is exactly the silent green this helper exists to prevent — and
/// passing an `Element` to `precacheImage` deadlocks on this setup.
///
/// Resolving the widget's own provider also means the `ResizeImage` wrapper the
/// component adds for decode sizing is honoured, so what is primed is what is
/// painted.
Future<void> _settleImages(WidgetTester tester) async {
  // Alternating a real-time window with a frame pump, rather than awaiting
  // inside `runAsync`. The read and the decode only progress under real async,
  // but the decoded frame is only *delivered* by a pump, so neither on its own
  // is enough: a fixed delay followed by pumps produced goldens with an empty
  // slot, and awaiting the image stream inside `runAsync` deadlocks because no
  // frame is pumped while it waits.
  for (int i = 0; i < 12; i++) {
    await tester.runAsync(
      () => Future<void>.delayed(const Duration(milliseconds: 50)),
    );
    await tester.pump();
    if (_allImagesPainted(tester)) break;
  }
  await tester.pump();
}

/// Whether every `Image` in the tree has actually painted a frame.
///
/// Asserted rather than assumed: a golden that captures a placeholder where a
/// picture belongs would pass forever while showing the wrong thing.
bool _allImagesPainted(WidgetTester tester) {
  final Iterable<RenderObject> images = find
      .byType(RawImage)
      .evaluate()
      .map((Element e) => e.renderObject!);
  if (images.isEmpty) return false;
  return images.every((RenderObject r) => (r as RenderImage).image != null);
}

Future<void> _pumpExplore(
  WidgetTester tester, {
  required String location,
  required MediaImageLoader loader,
  AppPreferences preferences = AppPreferences.defaults,
  List<SeasonDriverCard>? drivers,
}) async {
  await pumpApp(
    tester,
    initialLocation: location,
    surfaceSize: _device,
    clock: _clock,
    preferences: preferences,
    platformBrightness: Brightness.dark,
    disableAnimations: true,
    mediaLoader: loader,
    drivers: FakeDriverRepository(
      cards: (int season) => drivers ?? _drivers(),
      profile: (int season, String driverId) =>
          driverProfileFixture(season: season, driverId: driverId),
    ),
    constructors: FakeConstructorRepository(
      cards: (int season) => _teams(),
      profile: (int season, String constructorId) =>
          teamProfileFixture(season: season, constructorId: constructorId),
    ),
    circuits: FakeCircuitRepository(
      cards: (int season) => _circuits(),
      profile: (int season, String circuitId) =>
          circuitProfileFixture(season: season, circuitId: circuitId),
    ),
  );
  await _settleImages(tester);
}

void main() {
  setUpAll(() {
    _tmp = Directory.systemTemp.createTempSync('gv_media_goldens');
    _square = writePng(_tmp, 'square.png', bandedPng(160, 160));
    _wide = writePng(_tmp, 'wide.png', bandedPng(160, 90, bands: 3));
  });

  tearDownAll(() {
    // Best effort: the decoded images may still hold the files open, and on
    // Windows that makes the delete fail. A leftover temp directory is not a
    // test failure.
    try {
      if (_tmp.existsSync()) _tmp.deleteSync(recursive: true);
    } on FileSystemException {
      // Ignored deliberately.
    }
  });

  group('Explore rows with media', () {
    testWidgets('golden: explore drivers with loaded portraits', (
      WidgetTester tester,
    ) async {
      await _pumpExplore(
        tester,
        location: '/explore',
        loader: _CachedLoader(_square),
      );
      await expectLater(
        find.byType(ExploreScreen),
        matchesGoldenFile('goldens/explore_drivers_media_dark.png'),
      );
    });

    testWidgets('golden: explore drivers with no media at all', (
      WidgetTester tester,
    ) async {
      // The fallback every row falls back to, at the same size as the loaded
      // state above: the two images must differ only inside the leading slot.
      await _pumpExplore(
        tester,
        location: '/explore',
        loader: _CachedLoader(_square),
        drivers: _drivers(withMedia: false),
      );
      await expectLater(
        find.byType(ExploreScreen),
        matchesGoldenFile('goldens/explore_drivers_no_media.png'),
      );
    });

    testWidgets('golden: explore drivers when every image fails', (
      WidgetTester tester,
    ) async {
      // Must be visually identical to the no-media golden: a user cannot be
      // shown the difference between "there is no picture" and "the picture
      // did not arrive".
      await _pumpExplore(
        tester,
        location: '/explore',
        loader: _FailingLoader(),
      );
      await expectLater(
        find.byType(ExploreScreen),
        matchesGoldenFile('goldens/explore_drivers_media_failed.png'),
      );
    });

    testWidgets('golden: explore teams with loaded marks', (
      WidgetTester tester,
    ) async {
      await _pumpExplore(
        tester,
        location: '/explore/teams',
        loader: _CachedLoader(_square),
      );
      await expectLater(
        find.byType(ExploreScreen),
        matchesGoldenFile('goldens/explore_teams_media_dark.png'),
      );
    });

    testWidgets('golden: explore circuits with loaded layouts', (
      WidgetTester tester,
    ) async {
      await _pumpExplore(
        tester,
        location: '/explore/circuits',
        loader: _CachedLoader(_wide),
      );
      await expectLater(
        find.byType(ExploreScreen),
        matchesGoldenFile('goldens/explore_circuits_media_dark.png'),
      );
    });

    testWidgets('golden: explore drivers with loaded portraits, light theme', (
      WidgetTester tester,
    ) async {
      await _pumpExplore(
        tester,
        location: '/explore',
        loader: _CachedLoader(_square),
        preferences: const AppPreferences(
          language: AppLanguagePreference.system,
          theme: AppThemePreference.light,
          timeDisplay: TimeDisplayPreference.device,
        ),
      );
      await expectLater(
        find.byType(ExploreScreen),
        matchesGoldenFile('goldens/explore_drivers_media_light.png'),
      );
    });
  });

  group('acknowledgements', () {
    testWidgets('golden: acknowledgements with media credits', (
      WidgetTester tester,
    ) async {
      await pumpApp(
        tester,
        initialLocation: '/settings/acknowledgements',
        surfaceSize: _device,
        clock: _clock,
        platformBrightness: Brightness.dark,
        disableAnimations: true,
        mediaAttributions: const <MediaAttribution>[
          MediaAttribution(
            category: MediaCategory.portrait,
            attribution: 'GridView synthetic fixture',
            license: 'GridView-owned synthetic fixture',
          ),
          MediaAttribution(
            category: MediaCategory.circuitLayout,
            attribution: 'GridView synthetic layout',
            license: 'GridView-owned synthetic fixture',
          ),
        ],
      );
      await expectLater(
        find.byType(AcknowledgementsScreen),
        matchesGoldenFile('goldens/acknowledgements_with_credits.png'),
      );
    });
  });
}
